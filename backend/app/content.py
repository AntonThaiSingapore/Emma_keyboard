def public_level(level: dict) -> dict:
    """The JSON shape the frontend consumes (snake_case kept for one vocabulary)."""
    return {
        "id": level["id"],
        "title": level["title"],
        "subtitle": level["subtitle"],
        "mode": level["mode"],
        "keys": level["keys"],
        "target_count": level["target_count"],
        "spawn_interval": level["spawn_interval"],
        "fall_seconds": level["fall_seconds"],
        "seconds_per_char": level["seconds_per_char"],
        "max_on_screen": level["max_on_screen"],
        "lives": level["lives"],
        "multiplier": level["multiplier"],
        "bank": level["bank"],
    }