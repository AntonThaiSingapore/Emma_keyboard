"""Level definitions and typing content.

Everything the game shows lives here so the frontend stays a renderer and the
content can be tuned without touching the UI. `GET /api/levels` ships this as
JSON; the frontend never hard-codes a word, phrase or quote.

Level shape
-----------
mode          "letter" | "word" | "phrase"
bank          tokens drawn for that level (letter levels generate from `keys`)
keys          the characters the level trains — drives the on-screen keyboard
target_count  how many tokens must be destroyed to clear the level
spawn_interval  seconds between spawns
fall_seconds   seconds a token takes to travel the full field height
seconds_per_char  extra fall time granted per character beyond the first. A
                 58-character quote cannot be typed in the 9 seconds a single
                 letter is given, so long tokens get a budget proportional to
                 their length: fall = fall_seconds + seconds_per_char*(len-1).
max_on_screen  how many tokens may fall at once
lives          tokens allowed to reach the floor before the run ends
multiplier     score multiplier
"""

